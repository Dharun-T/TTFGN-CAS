// Helper to create a custom ad-hoc ICU patient case on the fly
export function createCustomPatientCase(params: {
  bed: string;
  nameAlias: string;
  age: number;
  gender: "Male" | "Female";
  careUnit: "MICU" | "SICU" | "CCU" | "CVICU" | "TSICU" | "NICU";
  admitDiagnosis: string;
  analyte: "Potassium" | "Glucose" | "Hemoglobin" | "Sodium" | "Creatinine";
  recentValue: number;
  deltaValue: number;
  hasDiuretic?: boolean;
  hasVasopressor?: boolean;
  hasInsulin?: boolean;
  sofaCardio?: number;
  sofaRenal?: number;
}): PatientCase {
  const unitsMap: Record<string, { unit: string; min: number; max: number; critHigh?: number; critLow?: number }> = {
    Potassium: { unit: "mEq/L", min: 3.5, max: 5.0, critHigh: 6.0, critLow: 3.0 },
    Glucose: { unit: "mg/dL", min: 70.0, max: 140.0, critHigh: 250.0, critLow: 60.0 },
    Hemoglobin: { unit: "g/dL", min: 12.0, max: 16.0, critLow: 7.0 },
    Sodium: { unit: "mEq/L", min: 135.0, max: 145.0, critHigh: 155.0, critLow: 125.0 },
    Creatinine: { unit: "mg/dL", min: 0.6, max: 1.3, critHigh: 2.5 },
  };

  const meta = unitsMap[params.analyte];
  const targetVal = Number((params.recentValue + params.deltaValue).toFixed(1));

  // Compute CAS estimate
  let baseScore = 0.22;
  if (params.analyte === "Potassium") {
    if (targetVal > 5.2) baseScore += (targetVal - 5.0) * 0.42;
    if (targetVal < 3.4) baseScore += (3.5 - targetVal) * 0.45;
  } else if (params.analyte === "Creatinine") {
    if (targetVal > 1.8) baseScore += (targetVal - 1.3) * 0.32;
  } else if (params.analyte === "Hemoglobin") {
    if (targetVal < 8.0) baseScore += (8.0 - targetVal) * 0.35;
  } else if (params.analyte === "Glucose") {
    if (targetVal > 190) baseScore += (targetVal - 180) * 0.003;
    if (targetVal < 65) baseScore += 0.55;
  } else if (params.analyte === "Sodium") {
    if (targetVal < 128 || targetVal > 150) baseScore += 0.45;
  }

  if (params.hasVasopressor) baseScore += 0.15;
  if (params.hasDiuretic) baseScore += 0.12;
  if ((params.sofaRenal || 0) >= 2) baseScore += 0.14;

  const cas = Math.min(0.97, Math.max(0.08, Number(baseScore.toFixed(3))));
  const band = cas >= 0.75 ? "HIGH" : cas >= 0.40 ? "MEDIUM" : "LOW";
  const id = `PATIENT-CUSTOM-${Date.now().toString().slice(-6)}`;

  return {
    id,
    nameAlias: params.nameAlias || "Patient " + params.bed,
    analyte: params.analyte,
    canonicalUnit: meta.unit,
    quadrant: cas >= 0.5 ? "True Positive" : "True Negative",
    cas,
    band,
    targetValue: targetVal,
    observedAction: cas >= 0.6,
    actionType: cas >= 0.6 ? `Emergency ${params.analyte} Protocol Action` : "Maintenance Clinical Regimen",
    timeToAction: cas >= 0.6 ? "0.8h" : "None",
    intervention: cas >= 0.6 ? `Clinician intervened within 1 hour post-result for ${params.analyte}` : "No acute intervention required",
    clinicalPostureRecommendation:
      cas >= 0.75
        ? `High predicted actionability (CAS ${cas}). Immediately prepare bedside corrective orders for impending ${params.analyte} abnormality, verify IV lines, and alert the attending physician.`
        : cas >= 0.40
        ? `Moderate predicted actionability (CAS ${cas}). Recommend closer monitoring, review concurrent medication interactions, and recheck trend in 4-6 hours.`
        : `Stable predicted actionability (CAS ${cas}). Maintain current ICU treatment plan and standard surveillance intervals.`,
    demographics: {
      age: params.age,
      gender: params.gender,
      careUnit: params.careUnit,
      bed: params.bed,
      admitDiagnosis: params.admitDiagnosis,
      sofaCardio: params.sofaCardio || 1,
      sofaRenal: params.sofaRenal || 1,
      codeStatus: "Full Code",
      losHours: 24,
      allergies: ["NKDA"],
    },
    vitals: {
      heartRate: params.hasVasopressor ? 112 : 82,
      bloodPressure: params.hasVasopressor ? "96/58" : "124/76",
      map: params.hasVasopressor ? 65 : 88,
      respiratoryRate: 18,
      spo2: 96,
      temperature: 37.0,
      gcs: 15,
      rhythm: "Normal Sinus Rhythm",
    },
    activeMedications: [
      ...(params.hasVasopressor ? [{ drug: "Norepinephrine IV", route: "IV Infusion" as const, dose: "0.12 mcg/kg/min", category: "vasopressor" as const }] : []),
      ...(params.hasDiuretic ? [{ drug: "Furosemide IV", route: "IV Push" as const, dose: "40 mg q12h", category: "diuretic" as const }] : []),
      ...(params.hasInsulin ? [{ drug: "Regular Insulin", route: "IV Infusion" as const, dose: "4.0 units/hr", category: "insulin" as const }] : []),
    ],
    comorbidities: [params.admitDiagnosis, "Critical Illness Exposure"],
    normalRange: { min: meta.min, max: meta.max },
    criticalThreshold: { high: meta.critHigh, low: meta.critLow },
    lookbackTrajectory: [
      { timeHoursAgo: -48, value: Number((params.recentValue - params.deltaValue * 1.5).toFixed(1)), label: "Day 1" },
      { timeHoursAgo: -24, value: Number((params.recentValue - params.deltaValue * 0.8).toFixed(1)), label: "Day 2" },
      { timeHoursAgo: -12, value: Number((params.recentValue - params.deltaValue * 0.3).toFixed(1)), label: "Day 2.5" },
      { timeHoursAgo: -0.5, value: params.recentValue, label: "Recent Draw" },
    ],
    targetReport: { time: "0h (Pending)", value: targetVal, status: cas >= 0.75 ? "Critical Predicted" : "Stable" },
    explainability: {
      timeDecayFactor: 0.92,
      gateLabWeight: 0.62,
      gateContextWeight: 0.38,
      tensorSynergy: 0.45,
      topPositive: [
        { feature: `Recent ${params.analyte} Velocity Delta`, impact: 0.38 },
        { feature: `${params.careUnit} ICU Clinical Acuity`, impact: 0.22 },
      ],
      topNegative: [
        { feature: "Baseline Physiological Reserve", impact: -0.15 },
      ],
    },
    orderSet: [
      {
        id: `ORD-CUST-${Date.now().toString().slice(-4)}1`,
        title: `Targeted ${params.analyte} Protocol Action`,
        details: `Specific clinical directive based on predicted ${params.analyte} trajectory value of ${targetVal} ${meta.unit}.`,
        category: "Medication",
        actionType: "Start",
        urgent: cas >= 0.75,
      },
      {
        id: `ORD-CUST-${Date.now().toString().slice(-4)}2`,
        title: `Verification Phlebotomy for ${params.analyte}`,
        details: `Follow-up verification draw scheduled post-intervention.`,
        category: "Diagnostic",
        actionType: "Order",
        urgent: false,
      },
    ],
    sbar: {
      situation: `Bed ${params.bed}: ${params.nameAlias} admitted with ${params.admitDiagnosis}, pending ${params.analyte} evaluation.`,
      background: `Monitored in ${params.careUnit}. Current vital signs: MAP ${params.hasVasopressor ? 65 : 88}, HR ${params.hasVasopressor ? 112 : 82}.`,
      assessment: `T-TFGN CAS is ${cas} (${band} Actionability).`,
      recommendation: `Follow predicted protocol recommendations and review automated CPOE orders.`,
    },
    concurrentLabs: {},
  };
}

